// Tarjima olish funksiyasi
export function t(
  key: string,
  lang: Language = 'cyr'
): string {
  const keys = key.split('.');
  let result: any = translations;
  
  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k];
    } else {
      console.warn(`Translation not found: ${key}`);
      return key;
    }
  }
  
  if (result && typeof result === 'object' && lang in result) {
    return result[lang];
  }
  
  console.warn(`Translation not found for language ${lang}: ${key}`);
  return key;
}

// Til nomlarini olish
export function getLanguageName(lang: Language): string {
  return languageNames[lang];
}

// Barcha tillar ro'yxati
export function getAvailableLanguages(): { code: Language; name: string }[] {
  return Object.entries(languageNames).map(([code, name]) => ({
    code: code as Language,
    name,
  }));
}
